export function exportToJson(report) {
  const jsonStr = JSON.stringify(report, null, 2);
  const blob = new Blob([jsonStr], { type: 'application/json' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `${(report.topic || 'trend-report').toLowerCase().replace(/\s+/g, '-')}-intelligence.json`;
  a.click();
  URL.revokeObjectURL(url);
}

export function exportToMarkdown(report) {
  const md = `# AI Trend Intelligence Report: ${report.topic}

**Category:** ${report.category || 'N/A'} | **Confidence:** ${report.confidence}% | **Momentum:** ${report.trendMomentum?.signal?.toUpperCase() || 'N/A'}
**Generated:** ${new Date().toLocaleDateString()} | **Analysis Source:** ${report._source === 'live' ? 'Live AI Synthesis' : 'Trend Database Model'}

---

## The Story in 10 Points
${(report.tenPoints || [])
  .map(p => `### ${p.num}. ${p.question}\n${p.answer}\n`)
  .join('\n')}

---

## Big Picture
**What is happening:**
${report.bigPicture?.whatIsHappening || ''}

**Why is it trending:**
${(report.bigPicture?.whyTrending || []).map(r => `- ${r}`).join('\n')}

**Why should you care:**
${report.bigPicture?.whyShouldICare || ''}

---

## Trend DNA
- **Origin (${report.trendDNA?.origin?.period}):** ${report.trendDNA?.origin?.event}
- **Trigger (${report.trendDNA?.trigger?.period}):** ${report.trendDNA?.trigger?.event}
- **Growth (${report.trendDNA?.growth?.period}):** ${report.trendDNA?.growth?.event}
- **Acceleration (${report.trendDNA?.acceleration?.period}):** ${report.trendDNA?.acceleration?.event}
- **Current State (${report.trendDNA?.now?.period}):** ${report.trendDNA?.now?.event}
- **Future (${report.trendDNA?.future?.period}):** ${report.trendDNA?.future?.event}

---

## Historical Milestones
${(report.timeline || [])
  .map(t => `- **${t.year}** (${t.date}): **${t.event}** — ${t.what} *(Impact: ${t.impact})*`)
  .join('\n')}

---

## Key People
${(report.people || [])
  .map(p => `- **${p.name}** (${p.role}, ${p.org}): ${p.contribution}`)
  .join('\n')}

---

## Major Problems & Gaps
${(report.problems || [])
  .map(p => `### [${p.category}] ${p.title}\n${p.description}\n- **Evidence:** ${p.evidence}\n- **Severity:** ${p.severity}\n`)
  .join('\n')}

---

## Opportunity Radar & Project Ideas
${(report.projectIdeas || [])
  .map(i => `### ${i.title}\n- **Problem:** ${i.problem}\n- **Solution:** ${i.solution}\n- **Target Users:** ${i.users}\n- **Difficulty:** ${i.difficulty}\n- **MVP Scope:** ${i.mvp}\n`)
  .join('\n')}

---

*Report generated by AI Trend Analyzer. Facts distinguished from AI scenario analysis.*
`;

  const blob = new Blob([md], { type: 'text/markdown' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `${(report.topic || 'trend-report').toLowerCase().replace(/\s+/g, '-')}-intelligence.md`;
  a.click();
  URL.revokeObjectURL(url);
}

