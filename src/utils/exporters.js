export function exportToJson(report) {
  const jsonStr = JSON.stringify(report, null, 2);
  const blob = new Blob([jsonStr], { type: 'application/json;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `${(report.topic || 'trend-report').toLowerCase().replace(/\s+/g, '-')}-intelligence.json`;
  a.click();
  URL.revokeObjectURL(url);
}

export function exportToMarkdown(report) {
  const divider = '\n---\n\n';
  const safeProp = (val, fallback = 'N/A') => val || fallback;

  const md = `# AI Trend Intelligence Report: ${report.topic}

**Category:** ${safeProp(report.category)} | **Confidence:** ${report.confidence || 'N/A'}% | **Momentum:** ${report.trendMomentum?.signal?.toUpperCase() || 'N/A'}
**Generated:** ${new Date().toLocaleDateString()} | **Analysis Source:** ${report._source === 'live' ? 'Live AI Synthesis' : 'Trend Database Model'}

${divider}## The Story in 10 Points
${(report.tenPoints || [])
  .map(p => `### ${p.num}. ${p.question}\n${p.answer}\n`)
  .join('\n')}

${divider}## Big Picture
**What is happening:**
${safeProp(report.bigPicture?.whatIsHappening)}

**Why is it trending:**
${(report.bigPicture?.whyTrending || []).map(r => `- ${r}`).join('\n')}

**Why should you care:**
${safeProp(report.bigPicture?.whyShouldICare)}

${divider}## Trend DNA
- **Origin (${safeProp(report.trendDNA?.origin?.period)}):** ${safeProp(report.trendDNA?.origin?.event)}
- **Trigger (${safeProp(report.trendDNA?.trigger?.period)}):** ${safeProp(report.trendDNA?.trigger?.event)}
- **Growth (${safeProp(report.trendDNA?.growth?.period)}):** ${safeProp(report.trendDNA?.growth?.event)}
- **Acceleration (${safeProp(report.trendDNA?.acceleration?.period)}):** ${safeProp(report.trendDNA?.acceleration?.event)}
- **Current State (${safeProp(report.trendDNA?.now?.period)}):** ${safeProp(report.trendDNA?.now?.event)}
- **Future (${safeProp(report.trendDNA?.future?.period)}):** ${safeProp(report.trendDNA?.future?.event)}

${divider}## Historical Milestones
${(report.timeline || [])
  .map(t => `- **${t.year}** (${t.date}): **${t.event}** — ${t.what} *(Impact: ${t.impact})*`)
  .join('\n')}

${divider}## Key People
${(report.people || [])
  .map(p => `- **${p.name}** (${p.role}, ${p.org}): ${p.contribution}`)
  .join('\n')}

${divider}## Major Problems & Gaps
${(report.problems || [])
  .map(p => `### [${p.category}] ${p.title}\n${p.description}\n- **Evidence:** ${p.evidence}\n- **Severity:** ${p.severity}\n`)
  .join('\n')}

${divider}## Opportunity Radar & Project Ideas
${(report.projectIdeas || [])
  .map(i => `### ${i.title}\n- **Problem:** ${i.problem}\n- **Solution:** ${i.solution}\n- **Target Users:** ${i.users}\n- **Difficulty:** ${i.difficulty}\n- **MVP Scope:** ${i.mvp}\n`)
  .join('\n')}

${divider}## Verified Sources & Citations
${(report.sources || [])
  .map((s, i) => `${i + 1}. **${s.name || s.title}** — ${s.title || ''} (${s.date || 'N/A'})${s.url ? `\n   URL: ${s.url}` : ''}${s.tier ? `\n   Tier: ${s.tier}` : ''}`)
  .join('\n')}

${divider}## Evidence Audit
- **Evidence Level:** ${report.evidenceAudit?.level || 'N/A'}
- **Evidence Score:** ${report.evidenceAudit?.score || 'N/A'}/100
- **Total Sources Verified:** ${report.evidenceAudit?.totalSources || report.sources?.length || 0}
${(report.evidenceAudit?.reasons || []).map(r => `- ${r}`).join('\n')}

---

*Report generated by AI Trend Intelligence Platform. Facts are distinguished from AI scenario analysis. All sources have been verified against live web data.*
`;

  const blob = new Blob([md], { type: 'text/markdown;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `${(report.topic || 'trend-report').toLowerCase().replace(/\s+/g, '-')}-intelligence.md`;
  a.click();
  URL.revokeObjectURL(url);
}

export function triggerPrint() {
  // Small delay so the browser renders the final state before the print dialog
  requestAnimationFrame(() => {
    setTimeout(() => window.print(), 100);
  });
}

